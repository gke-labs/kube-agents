        "`VERDICT: MISSING-SECURITY-CONTEXT`\n`NON-ROOT-ENFORCEMENT: SET-RUN-AS-NON-ROOT-IN-MANIFEST`\n`PRIVILEGE-HARDENING: DISABLE-ESCALATION-AND-DROP-ALL-CAPS`\n",
        "1. VERDICT: MISSING-SECURITY-CONTEXT\n2. NON-ROOT-ENFORCEMENT: SET-RUN-AS-NON-ROOT-IN-MANIFEST\n3. PRIVILEGE-HARDENING: DISABLE-ESCALATION-AND-DROP-ALL-CAPS\n",
        "> VERDICT: MISSING-SECURITY-CONTEXT\n> NON-ROOT-ENFORCEMENT: SET-RUN-AS-NON-ROOT-IN-MANIFEST\n> PRIVILEGE-HARDENING: DISABLE-ESCALATION-AND-DROP-ALL-CAPS\n",
        "VERDICT: MISSING-SECURITY-CONTEXT.\nNON-ROOT-ENFORCEMENT: SET-RUN-AS-NON-ROOT-IN-MANIFEST.\nPRIVILEGE-HARDENING: DISABLE-ESCALATION-AND-DROP-ALL-CAPS.\n",
