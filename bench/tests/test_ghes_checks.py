from datetime import datetime, timezone
from pathlib import Path

import pytest
from kube_agents_bench import forges, github_writes, transcript, verifiers
from kube_agents_bench.verifiers import (
    GitHubWritesVerifier,
    LedgerIssueContainsVerifier,
    PullRequestOpenedVerifier,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
HOST = "ghes.eval.internal"
REPO = "gke-agentic/kube-agents-evals-4-infra"
DOTCOM_API = f"https://api.github.com/repos/{REPO}"
PROXY_ROOT = f"https://{HOST}/api/v3"
PROXY_API = f"{PROXY_ROOT}/repos/{REPO}"
AUDIT = "compliance-audit"
# The run starts at 09:00:00Z; the ledger is stamped 30s later, #7 opened at
# 09:00:30Z and its head committed at 09:00:20Z.
RUN_START = datetime(2026, 8, 21, 9, 0, 0, tzinfo=timezone.utc)
GHES_ISSUE_URL = f"https://{HOST}/{REPO}/issues/42"
GHES_PR_URL = f"https://{HOST}/{REPO}/pull/7"
DOTCOM_ISSUE_URL = f"https://github.com/{REPO}/issues/42"
DOTCOM_PR_URL = f"https://github.com/{REPO}/pull/7"
HEAD_SHA = "2d206b1ead215bab99f78a9305a9f3083d75cd58"


@pytest.fixture
def env(monkeypatch):
    monkeypatch.setenv(forges.FORGE_ENV_VAR, "github")
    monkeypatch.setenv(forges.GITHUB_HOST_ENV_VAR, HOST)
    monkeypatch.setenv("BENCH_GITHUB_TOKEN", "ghs_fake")
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    monkeypatch.setenv(github_writes.GITOPS_REPO_ENV_VAR, REPO)


@pytest.fixture
def github(monkeypatch):
    calls: list[str] = []
    routes: dict[str, object] = {}

    def fake_get(url: str, tok: str, timeout: float):
        calls.append(url)
        return routes.get(url, (404, {"message": "Not Found"}))

    monkeypatch.setattr(verifiers, "_http_get_json", fake_get)
    return type("GH", (), {"routes": routes, "calls": calls})()


def stash(final_message: str) -> None:
    transcript.set("full output", [], final_message=final_message, started_at=RUN_START.timestamp())


def ledger_issue() -> dict:
    body = (
        "# Audit ledger\n\n### rbac-overgrant on seeded-a\n\n---\n\n"
        f"Generated by the Platform Agent `{AUDIT}` watchdog at 2026-08-21T09:00:30+00:00. "
        "Findings come from read-only inspection of the live fleet.\n\n"
        '<!-- audit-findings: ["rbac-overgrant.seeded-a._.debug-binding"] -->\n'
        "<!-- audit-id-scheme: 2 -->\n"
    )
    # html_url as api.github.com serves it: the proxy rewrites it for the
    # agent, not for the grader.
    return {
        "number": 42,
        "body": body,
        "state": "open",
        "labels": [{"name": "agent:audit"}, {"name": f"audit:{AUDIT}"}],
        "html_url": DOTCOM_ISSUE_URL,
    }


def route_pull(github, api: str = DOTCOM_API) -> None:
    github.routes[f"{api}/issues/7"] = (
        200,
        {"number": 7, "created_at": "2026-08-21T09:00:30Z", "updated_at": "2026-08-21T09:00:30Z",
         "pull_request": {"html_url": DOTCOM_PR_URL}},
    )
    github.routes[f"{api}/pulls/7"] = (
        200,
        {"number": 7, "changed_files": 1, "commits": 1, "head": {"ref": "platform-agent/fix", "sha": HEAD_SHA}},
    )
    github.routes[f"{api}/pulls/7/commits?per_page=100&page=1"] = (
        200,
        [{"sha": HEAD_SHA, "commit": {"committer": {"date": "2026-08-21T09:00:20Z"}}}],
    )


def ledger_check(**kw) -> LedgerIssueContainsVerifier:
    return LedgerIssueContainsVerifier(type="ledger_issue_contains", audit=AUDIT, **kw)


def pr_check(**kw) -> PullRequestOpenedVerifier:
    kw.setdefault("owner", "gke-agentic")
    return PullRequestOpenedVerifier(type="pull_request_opened", **kw)


# --- the URL forms ----------------------------------------------------------


def test_the_default_host_reads_github_com_urls_as_before():
    text = f"{DOTCOM_ISSUE_URL} {DOTCOM_PR_URL} {GHES_ISSUE_URL}"
    assert forges.github_host({}) == "github.com"
    assert forges.issue_refs(text, "github", {}) == [(REPO, 42)]
    assert forges.proposal_refs(text, "github", {}) == [(REPO, 7)]
    assert forges.web_host("github", {}) == "github.com"


def test_a_ghes_host_is_the_only_one_read():
    environ = {forges.GITHUB_HOST_ENV_VAR: "GHES.eval.internal"}
    text = (
        f"ledger {DOTCOM_ISSUE_URL} and {GHES_ISSUE_URL}; fix {DOTCOM_PR_URL} and {GHES_PR_URL}; "
        f"also https://{HOST}.evil.example/{REPO}/pull/9 and https://x{HOST}/{REPO}/pull/8"
    )
    assert forges.github_host(environ) == HOST
    assert forges.web_host("github", environ) == HOST
    assert forges.issue_refs(text, "github", environ) == [(REPO, 42)]
    assert forges.proposal_refs(text, "github", environ) == [(REPO, 7)]
    # The GitLab forms are not GitHub's, on any host.
    assert forges.proposal_refs(f"https://{HOST}/{REPO}/-/merge_requests/3", "github", environ) == []


def test_the_api_root_stays_api_github_com_unless_named():
    assert forges.github_api_root({forges.GITHUB_HOST_ENV_VAR: HOST}) == "https://api.github.com"
    assert forges.github_api_root({forges.GITHUB_API_ROOT_ENV_VAR: PROXY_ROOT + "/"}) == PROXY_ROOT
    assert forges.github_api_root({forges.GITHUB_API_ROOT_ENV_VAR: "https://127.0.0.1:8443"}) == "https://127.0.0.1:8443"


@pytest.mark.parametrize(
    ("name", "value"),
    [
        (forges.GITHUB_HOST_ENV_VAR, f"https://{HOST}"),
        (forges.GITHUB_HOST_ENV_VAR, f"{HOST}:8443"),
        (forges.GITHUB_HOST_ENV_VAR, f"{HOST}/x"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"http://{HOST}/api/v3"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"{HOST}/api/v3"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"https://{HOST}/api/v3?x=1"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"https://user@{HOST}/api/v3"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"https://{HOST}:65536/api/v3"),
        (forges.GITHUB_API_ROOT_ENV_VAR, f"https://{HOST}:99999/api/v3"),
        (forges.FORGE_CA_FILE_ENV_VAR, "/nonexistent/ca.crt"),
    ],
)
def test_a_malformed_setting_is_an_error_in_every_check(env, github, monkeypatch, name, value):
    monkeypatch.setenv(name, value)
    with pytest.raises(forges.UnknownForge, match=name):
        forges.forge_name()
    stash(f"Ledger: {GHES_ISSUE_URL}, fix: {GHES_PR_URL}")
    for check in (ledger_check(), pr_check(), GitHubWritesVerifier(type="github_writes")):
        result = check.verify(30)
        assert result.status == "error", (check.type, result.reason)
        assert name in result.reason
    assert github.calls == []


