"""The forge checks on a GitHub Enterprise Server host, and the private CA.

``BENCH_FORGE=github`` with ``BENCH_GITHUB_HOST`` set: the reply's issue and
pull request URLs must be on that host, and the checks still read the data
from api.github.com, because the eval's GHES host is a forwarding proxy to
github.com (``hack/ghes-proxy``). ``BENCH_GITHUB_API_ROOT`` moves the reads,
for example through the proxy, and ``BENCH_FORGE_CA_FILE`` adds a private CA
for an API host it signed. The payload shapes are GitHub's, as in
``test_verifiers.py`` and ``test_github_writes.py``.
"""

from __future__ import annotations

import http.server
import json
