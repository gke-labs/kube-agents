# --- BENCH_FORGE_CA_FILE ----------------------------------------------------


@pytest.fixture
def private_ca_server(tmp_path):
    """An HTTPS server on 127.0.0.1 with a certificate for ``localhost`` that
    a private CA signed, made by hack/ghes-proxy/make-certs.sh."""
    if not shutil.which("openssl"):
        pytest.skip("openssl is not on PATH")
    certs = tmp_path / "certs"
    subprocess.run(
        ["bash", str(REPO_ROOT / "hack" / "ghes-proxy" / "make-certs.sh"), "localhost", str(certs), "1"],
        check=True,
        capture_output=True,
    )

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802 - the stdlib's name
            body = json.dumps({"path": self.path, "auth": self.headers.get("Authorization")}).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    context.load_cert_chain(certs / "tls.crt", certs / "tls.key")
    server.socket = context.wrap_socket(server.socket, server_side=True)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    yield f"https://localhost:{server.server_address[1]}", certs / "ca.crt"
    # tls.crt sits beside ca.crt; the leaf test below reads it from there.
    server.shutdown()
    server.server_close()


def test_a_private_ca_is_trusted_only_when_named(private_ca_server, monkeypatch):
    url, ca = private_ca_server
    monkeypatch.setattr(verifiers, "_FORGE_READ_RETRY_PAUSE_SEC", 0)
    with pytest.raises(OSError, match="CERTIFICATE_VERIFY_FAILED"):
        verifiers._http_get_json(f"{url}/repos/a/b", "ghs_fake", 5)

    monkeypatch.setenv(forges.FORGE_CA_FILE_ENV_VAR, str(ca))
    status, payload = verifiers._http_get_json(f"{url}/repos/a/b", "ghs_fake", 5)
    assert status == 200
    assert payload == {"path": "/repos/a/b", "auth": "Bearer ghs_fake"}


def test_the_ca_file_adds_to_the_system_cas(tmp_path, private_ca_server):
    _, ca = private_ca_server
    context = forges.forge_ssl_context({forges.FORGE_CA_FILE_ENV_VAR: str(ca)})
    assert context is not None
    assert context.verify_mode == ssl.CERT_REQUIRED and context.check_hostname
    assert forges.forge_ssl_context({}) is None
    not_pem = tmp_path / "not-a-ca.crt"
    not_pem.write_text("not a certificate\n")
    with pytest.raises(forges.UnknownForge, match=forges.FORGE_CA_FILE_ENV_VAR):
        forges.forge_ssl_context({forges.FORGE_CA_FILE_ENV_VAR: str(not_pem)})


def test_a_bad_ca_file_is_an_error_on_a_gitlab_run_too(monkeypatch, tmp_path):
    monkeypatch.setenv(forges.FORGE_ENV_VAR, "gitlab")
    monkeypatch.setenv("BENCH_GITLAB_TOKEN", "glpat-fake")
    monkeypatch.setenv(forges.FORGE_CA_FILE_ENV_VAR, str(tmp_path / "missing.crt"))
    stash(f"Ledger: https://gitlab.com/{REPO}/-/issues/1")
    result = ledger_check().verify(30)
    assert result.status == "error"
    assert forges.FORGE_CA_FILE_ENV_VAR in result.reason


def test_the_server_certificate_is_refused_as_the_ca(private_ca_server):
    """make-certs.sh writes tls.crt beside ca.crt. The leaf loads as a
    certificate, but no chain can be built from it, so every read would fail
    with an error that names no setting: it is refused here instead."""
    _, ca = private_ca_server
    leaf = ca.parent / "tls.crt"
    with pytest.raises(forges.UnknownForge, match="no CA certificate"):
        forges.forge_ssl_context({forges.FORGE_CA_FILE_ENV_VAR: str(leaf)})


def test_make_certs_shows_why_openssl_failed(tmp_path):
    """A failed openssl step prints openssl's own message, not nothing."""
    fake = tmp_path / "bin"
    fake.mkdir()
    (fake / "openssl").write_text("#!/bin/sh\necho 'unknown option -addext' >&2\nexit 1\n")
    (fake / "openssl").chmod(0o755)
    result = subprocess.run(
        ["bash", str(REPO_ROOT / "hack" / "ghes-proxy" / "make-certs.sh"), "localhost", str(tmp_path / "out")],
        capture_output=True,
        text=True,
        env={"PATH": f"{fake}:/usr/bin:/bin"},
    )
    assert result.returncode != 0
    assert "unknown option -addext" in result.stderr
    assert "'openssl req' failed" in result.stderr
    assert not (tmp_path / "out" / "tls.key").exists()


def test_a_ca_file_that_does_not_verify_the_host_is_named(private_ca_server, tmp_path, monkeypatch):
    """Another CA (a ca.crt from an earlier make-certs.sh run) loads as a CA
    and then fails every read; the error names BENCH_FORGE_CA_FILE, so it does
    not read the same as a run with no CA file at all."""
    url, _ = private_ca_server
    other = tmp_path / "other"
    subprocess.run(
        ["bash", str(REPO_ROOT / "hack" / "ghes-proxy" / "make-certs.sh"), "localhost", str(other), "1"],
        check=True,
        capture_output=True,
    )
    monkeypatch.setattr(verifiers, "_FORGE_READ_RETRY_PAUSE_SEC", 0)
    monkeypatch.setenv(forges.FORGE_CA_FILE_ENV_VAR, str(other / "ca.crt"))
    with pytest.raises(OSError) as raised:
        verifiers._http_get_json(f"{url}/repos/a/b", "ghs_fake", 5)
    message = str(raised.value)
    assert forges.FORGE_CA_FILE_ENV_VAR in message
    assert "does not verify localhost:" in message

    # With no CA file set, the error stays urllib's own.
    monkeypatch.delenv(forges.FORGE_CA_FILE_ENV_VAR)
    with pytest.raises(OSError) as raised:
        verifiers._http_get_json(f"{url}/repos/a/b", "ghs_fake", 5)
    assert forges.FORGE_CA_FILE_ENV_VAR not in str(raised.value)
