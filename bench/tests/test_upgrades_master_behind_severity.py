"""Pins the severity check of ``upgrades-master-behind-offered-elsewhere``.

The check grades the lagging cluster's ``master-behind`` finding as major by
the one phrase ``seeded-b) | major`` over the ledger's findings table. The
cluster's correct ``upgrade-blocked`` finding renders a critical row with the
same ``cluster-seeded-b)`` tail beside it, so a phrase on that tail cannot
forbid a severity. Every fixture is graded through
``LedgerIssueContainsVerifier.verify()`` with the one HTTP GET faked, as
``test_verifiers.py`` does, so the test runs the check the verifier runs.
"""

from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest
import yaml

from kube_agents_bench import transcript, verifiers
from kube_agents_bench.verifiers import LedgerIssueContainsVerifier

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "agents" / "platform" / "skills" / "fleet-audit" / "scripts")]
import audit_report  # noqa: E402
import patch_readiness  # noqa: E402

CASE = REPO / "bench" / "tasks" / "upgrades-master-behind-offered-elsewhere" / "task.yaml"
FLEET = REPO / "bench" / "tf" / "fleet" / "main.tf"
CHECK_NAME = "the-lagging-cluster-is-graded-major-not-critical"
AUDIT = "security-patch-orchestrator"
FORGE_REPO = "kube-agents-evals-36-infra"
ISSUE = 348
RUN_START = datetime(2026, 10, 29, 0, 40, 0, tzinfo=timezone.utc).timestamp()
GENERATED_AT = "2026-10-29T00:53:41.681474+00:00"
PREFIX = "kube-agents-evals-36-us-central1-a-"


def _check() -> dict:
    spec = yaml.safe_load(CASE.read_text())["verification_spec"]
    (entry,) = [e for e in spec if e["name"] == CHECK_NAME]
    return entry["check"]


def _row(check: str, cluster: str, severity: str) -> str:
    """One findings-table row, rendered by the renderer the audit uses."""
    fid = f"{check}.{PREFIX}{cluster}._.cluster-{cluster}"
    finding = {
        "id": fid,
        "severity": severity,
        "cluster": f"kube-agents-evals-36/us-central1-a/{cluster}",
    }
    return audit_report._index_row(finding, audit_report.STATE_OPEN, None)


def _ledger(rows: list[tuple[str, str, str]]) -> str:
    """A body in the renderer's shape: findings table, footer, hidden id block."""
    ids = sorted(f"{c}.{PREFIX}{cl}._.cluster-{cl}" for c, cl, _ in rows)
    table = "\n".join(_row(*r) for r in rows)
    return (
        "## Findings\n\n| Finding | Severity | Cluster | State |\n"
        "| ------- | -------- | ------- | ----- |\n"
        f"{table}\n\n---\n\n"
        f"Generated by the Platform Agent `{AUDIT}` watchdog at {GENERATED_AT}. "
        "Findings come from read-only inspection of the live fleet.\n\n"
        f"<!-- audit-findings: {json.dumps(ids, separators=(',', ':'))} -->\n"
        "<!-- audit-id-scheme: 6 -->\n"
    )


@pytest.fixture
def forge(monkeypatch):
    monkeypatch.setenv("BENCH_GITHUB_TOKEN", "ghs_fake")
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    monkeypatch.delenv("BENCH_FORGE", raising=False)
    routes: dict[str, object] = {}

    def fake_get(url: str, tok: str, timeout: float):
        return routes.get(url, (404, {"message": "Not Found"}))

    monkeypatch.setattr(verifiers, "_http_get_json", fake_get)
    return routes


def _grade(routes: dict, body: str) -> verifiers.VerificationResult:
    routes[f"https://api.github.com/repos/gke-agentic/{FORGE_REPO}/issues/{ISSUE}"] = (
        200,
        {"number": ISSUE, "body": body, "labels": [{"name": f"audit:{AUDIT}"}]},
    )
    transcript.set(
        "full output",
        [],
        final_message=(
            "Upgrade & patch readiness: 11 findings (1 critical) across 5 clusters — "
            f"https://github.com/gke-agentic/{FORGE_REPO}/issues/{ISSUE}"
        ),
        started_at=RUN_START,
    )
    return LedgerIssueContainsVerifier(**_check()).verify(5.0)


OTHER_ROWS = [
    ("master-behind", "seeded-a", "major"),
    ("no-notifications", "seeded-a", "minor"),
    ("no-notifications", "seeded-b", "minor"),
]


def test_the_fixture_leaves_master_behind_the_only_major_on_the_cluster():
    """The check's one phrase is master-behind's row only while this holds.

    no-channel and blocking-exclusion are the Cluster-object checks the
    collector can grade major; the first needs a cluster off every channel,
    the second a blocking exclusion scope. The other major checks render on
    a NodePool object. A change here opens the check to a critical
    master-behind beside another major row, so it fails before the night does.
    """
    fleet = FLEET.read_text()
    seeded_b = fleet[fleet.index('resource "google_container_cluster" "seeded_b"') :]
    seeded_b = seeded_b[: seeded_b.index("\n}\n")]
    assert re.search(r'channel\s*=\s*"REGULAR"', seeded_b)
    assert re.search(r'scope\s*=\s*"NO_MINOR_UPGRADES"', seeded_b)
    assert "NO_MINOR_UPGRADES" not in patch_readiness.BLOCKING_EXCLUSION_SCOPES
    major = {k for k, v in patch_readiness.SEVERITY.items() if v == patch_readiness.MAJOR}
    assert major == {"no-channel", "no-autoupgrade", "stale-image-type"}


PASSING = {
    "nightly: master-behind major beside upgrade-blocked critical": [
        ("upgrade-blocked", "seeded-b", "critical"),
        ("master-behind", "seeded-b", "major"),
        *OTHER_ROWS,
    ],
    "master-behind major alone": [("master-behind", "seeded-b", "major"), *OTHER_ROWS],
}

FAILING = {
    "master-behind graded critical": [("master-behind", "seeded-b", "critical"), *OTHER_ROWS],
    "master-behind critical beside upgrade-blocked critical": [
        ("upgrade-blocked", "seeded-b", "critical"),
        ("master-behind", "seeded-b", "critical"),
        *OTHER_ROWS,
    ],
    "no master-behind row on seeded-b": OTHER_ROWS,
    "a major row on another cluster only": [
        ("master-behind", "seeded-b", "critical"),
        ("master-behind", "seeded-c", "major"),
        *OTHER_ROWS,
    ],
}


@pytest.mark.parametrize("rows", PASSING.values(), ids=list(PASSING))
def test_a_major_master_behind_row_passes(forge, rows):
    res = _grade(forge, _ledger(rows))
    assert res.status == "pass", res.reason


@pytest.mark.parametrize("rows", FAILING.values(), ids=list(FAILING))
def test_no_major_row_on_the_lagging_cluster_fails(forge, rows):
    res = _grade(forge, _ledger(rows))
    assert res.status == "fail", res.reason
    assert "required phrases absent" in res.reason
