"""Pins the binding of ``security-expiring-node-bootstrap-and-webhook-certs``.

The case's ledger objectives must fail a ledger that files the planted
configuration under another check and an accepted check on another object,
and pass one finding that carries both. The pair of objectives the case
first had (a body phrase for the object, a slug among all finding ids)
passed the first ledger, which is the defect the finding scope closes. Every
fixture is graded through ``LedgerIssueContainsVerifier.verify()`` with the
one HTTP GET faked, as ``test_verifiers.py`` does.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

import pytest
import yaml

from kube_agents_bench import transcript, verifiers
from kube_agents_bench.verifiers import LedgerIssueContainsVerifier

REPO = Path(__file__).resolve().parents[2]
CASE = REPO / "bench" / "tasks" / "security-expiring-node-bootstrap-and-webhook-certs" / "task.yaml"
AUDIT = "compliance-audit"
FORGE_REPO = "kube-agents-evals-36-infra"
ISSUE = 61
CLUSTER = "kube-agents-evals-36-us-central1-a-platform-agent-host"
PLANTED = "ValidatingWebhookConfiguration/bench-expiring-webhook-ca"
OTHER = "ValidatingWebhookConfiguration/other-webhook"
ACCEPTED_CHECK = "webhook-ca-bundle-expired"
UNRELATED_CHECK = "webhook-fail-open"
RUN_START = datetime(2026, 11, 6, 16, 26, 0, tzinfo=timezone.utc).timestamp()
GENERATED_AT = "2026-11-06T16:37:49.000000+00:00"


def _ledger_objectives() -> list[dict]:
    spec = yaml.safe_load(CASE.read_text())["verification_spec"]
    return [e for e in spec if e["role"] == "objective" and e["check"]["type"] == "ledger_issue_contains"]


def _finding(check: str, obj: str) -> tuple[str, str]:
    """One cluster-scoped finding the way audit_report.py renders it: the
    anchor, the heading with the id marker, and the Where: line, whose
    namespace slot reads _cluster-scoped_ for an object with none."""
    fid = f"{check}.{CLUSTER}._.{obj.lower().replace('/', '-')}"
    block = (
        f'<a id="user-content-finding-{fid}"></a>\n\n'
        f"#### {check} on {obj} <!-- finding:{fid} -->\n\n"
        f"- **Where:** `{CLUSTER}` / _cluster-scoped_ — `{obj}`\n"
        f"- **Impact:** the agent's sentence about {obj}.\n"
        "- **Evidence:**\n\n```\n# (no command supplied)\n---\nkind: ValidatingWebhookConfiguration\n```\n\n"
    )
    return fid, block


def _ledger(findings: list[tuple[str, str]]) -> str:
    ids = sorted(fid for fid, _ in findings)
    body = "".join(block for _, block in findings)
    return (
        f"# Audit ledger\n\n{body}\n---\n\n"
        f"Generated by the Platform Agent `{AUDIT}` watchdog at {GENERATED_AT}. "
        "Findings come from read-only inspection of the live fleet.\n\n"
        f"<!-- audit-findings: {json.dumps(ids, separators=(',', ':'))} -->\n"
        "<!-- audit-id-scheme: 6 -->\n"
    )


@pytest.fixture
def forge(monkeypatch):
    monkeypatch.setenv("BENCH_GITHUB_TOKEN", "ghs_fake")
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    monkeypatch.delenv("BENCH_FORGE", raising=False)
    routes: dict[str, object] = {}

    def fake_get(url: str, tok: str, timeout: float):
        return routes.get(url, (404, {"message": "Not Found"}))

    monkeypatch.setattr(verifiers, "_http_get_json", fake_get)
    return routes


def _grade_all(routes: dict, body: str) -> dict[str, verifiers.VerificationResult]:
    routes[f"https://api.github.com/repos/gke-agentic/{FORGE_REPO}/issues/{ISSUE}"] = (
        200,
        {"number": ISSUE, "body": body, "labels": [{"name": f"audit:{AUDIT}"}]},
    )
    transcript.set(
        "full output",
        [],
        final_message=(
            "Security and RBAC posture audit: 2 findings across 1 cluster — "
            f"https://github.com/gke-agentic/{FORGE_REPO}/issues/{ISSUE}"
        ),
        started_at=RUN_START,
    )
    return {e["name"]: LedgerIssueContainsVerifier(**e["check"]).verify(5.0) for e in _ledger_objectives()}


def test_the_case_reads_its_ledger_with_at_least_one_objective():
    assert _ledger_objectives(), "the case grades the ledger with no objective"


def test_the_configuration_under_another_check_and_the_check_on_another_object_fail(forge):
    """The hole the unpaired pair left: the object is on the ledger (under an
    unrelated check) and an accepted check is on the ledger (on another
    object), and no finding carries both."""
    body = _ledger([_finding(UNRELATED_CHECK, PLANTED), _finding(ACCEPTED_CHECK, OTHER)])
    results = _grade_all(forge, body)
    failed = {name: res.reason for name, res in results.items() if res.status == "fail"}
    assert failed, {name: res.status for name, res in results.items()}
    assert any(PLANTED in reason for reason in failed.values()), failed


def test_one_finding_of_an_accepted_check_on_the_configuration_passes(forge):
    body = _ledger([_finding(UNRELATED_CHECK, OTHER), _finding(ACCEPTED_CHECK, PLANTED)])
    results = _grade_all(forge, body)
    assert all(res.status == "pass" for res in results.values()), {
        name: (res.status, res.reason) for name, res in results.items()
    }
