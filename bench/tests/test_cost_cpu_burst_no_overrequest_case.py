"""The id phrases of cost-cpu-burst-no-overrequest, graded by the case's own check.

The case forbids a finding id for `cpu-burst` and for `cpu-flat`. The ledger's
validator admits a workload finding with an empty namespace, and its id then
has `_` in the namespace segment. A phrase that holds the namespace is in no
such id, and the case then passes on an audit that files the finding. So the
case forbids the object segment only.

Each test builds a ledger with the parts that the verifier reads (the list of
finding ids and the stamp), with ids as the audit spells them, and grades it
with the check that the case file holds. No test calls GitHub: the one read of
the verifier gets a stand-in.

The phrases do not catch a worker that spells the object in another way
(another kind word, or the namespace inside the object). That limit is the
case's, and no test here covers it.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest
import yaml
from devops_bench.verification.spec import parse_node

from kube_agents_bench import transcript, verifiers

CASE_ID = "cost-cpu-burst-no-overrequest"
REPO_ROOT = Path(__file__).resolve().parents[2]
TASK = REPO_ROOT / "bench" / "tasks" / CASE_ID / "task.yaml"
AUDIT_SCRIPTS = REPO_ROOT / "agents" / "platform" / "skills" / "fleet-audit" / "scripts"
FLEET_FIXTURES = REPO_ROOT / "bench" / "tf" / "fleet" / "fixtures.json"
FIXTURE_ROLE = "cpu-burst-and-flat"
CHECK_NAME = "the-burst-is-not-an-overrequest"
AUDIT = "fleet-wide-cost-analysis"

# The two planted Deployments and their namespace, and the two spellings of the
# namespace that the validator admits on a workload finding.
DEPLOYMENTS = ("cpu-burst", "cpu-flat")
NAMESPACE = "seeded-cpu-cycle"
NAMESPACE_SPELLINGS = (NAMESPACE, "")
# The phrases of the case before this test: they held the namespace segment.
PHRASES_WITH_THE_NAMESPACE = [f"{NAMESPACE}.deployment-{name}" for name in DEPLOYMENTS]
# Cluster segments of several lengths. The longest ones make an id over the
# limit, so `published_id` cuts it, and the tests show that the cut keeps the
# object segment.
CLUSTER_NAMES = ["seeded-a"] + ["p" * length + "-us-central1-a-seeded-a" for length in (6, 14, 22, 30, 42, 70)]

# The run starts, and the ledger is stamped 30 seconds later.
RUN_START = datetime(2026, 8, 21, 9, 0, 0, tzinfo=timezone.utc).timestamp()
LEDGER_STAMP = "2026-08-21T09:00:30+00:00"
LEDGER_URL = "https://github.com/gke-agentic/kube-agents-evals-infra/issues/42"
LEDGER_API = "https://api.github.com/repos/gke-agentic/kube-agents-evals-infra/issues/42"
LEDGER_NUMBER = 42
VERIFY_TIMEOUT_SECONDS = 5.0


@pytest.fixture(scope="module")
def audit_report():
    sys.path.insert(0, str(AUDIT_SCRIPTS))
    try:
        import audit_report as module
    finally:
        sys.path.remove(str(AUDIT_SCRIPTS))
    return module


@pytest.fixture(scope="module")
def check() -> dict:
    case = yaml.safe_load(TASK.read_text())
    [entry] = [entry for entry in case["verification_spec"] if entry["name"] == CHECK_NAME]
    return entry["check"]


@pytest.fixture(autouse=True)
def _clean_stash():
    transcript.clear()
    yield
    transcript.clear()


@pytest.fixture
def ledger(monkeypatch, audit_report):
    """Give the verifier a ledger with these finding ids, as the one issue that the run's report names."""

    def put(finding_ids: list[str]) -> None:
        body = (
            "# Audit ledger\n\n### Findings\n\n"
            "\n---\n\n"
            f"Generated by the Platform Agent `{AUDIT}` watchdog at {LEDGER_STAMP}. "
            "Findings come from read-only inspection of the live fleet; every one "
            "carries the exact command it was derived from.\n\n"
            f"<!-- audit-findings: {json.dumps(sorted(set(finding_ids)), separators=(',', ':'))} -->\n"
            f"<!-- audit-id-scheme: {audit_report.ID_SCHEME} -->\n"
        )
        issue = {"number": LEDGER_NUMBER, "body": body, "labels": [{"name": f"audit:{AUDIT}"}]}
        routes = {LEDGER_API: (200, issue)}
        monkeypatch.setattr(verifiers, "_http_get_json", lambda url, token, timeout: routes.get(url, (404, {"message": "Not Found"})))
        monkeypatch.setenv("BENCH_GITHUB_TOKEN", "ghs_fake")
        monkeypatch.delenv("GITHUB_TOKEN", raising=False)
        transcript.set("full output", [], final_message=f"The audit is done. Ledger: {LEDGER_URL}", started_at=RUN_START)

    return put


def _id(audit_report, cluster: str, namespace: str, obj: str) -> str:
    return audit_report.published_id({"check": "overrequest", "cluster": cluster, "namespace": namespace, "object": obj})


def _family_id(audit_report, cluster: str) -> str:
    """The finding that each run on a pool project files; it shows that the run wrote a ledger."""
    return _id(audit_report, cluster, "seeded-family", "Deployment/calibration")


def _grade(check: dict, **changes):
    return parse_node({**check, **changes}).verify(VERIFY_TIMEOUT_SECONDS)


def _phrase_for(check: dict, deployment: str) -> str:
    """The one forbidden phrase of the case that is for this Deployment."""
    [phrase] = [phrase for phrase in check["forbidden_phrases"] if deployment in phrase]
    return phrase


def test_the_case_forbids_no_phrase_with_the_namespace(check) -> None:
    assert check["scope"] == "finding_ids"
    assert [phrase for phrase in check["forbidden_phrases"] if NAMESPACE in phrase] == []
    for deployment in DEPLOYMENTS:
        _phrase_for(check, deployment)


def test_no_other_fleet_object_has_one_of_the_two_names() -> None:
    """The phrases hold no namespace, so they match in each namespace of each cluster: the names must be unique on the fleet."""
    roles = json.loads(FLEET_FIXTURES.read_text())["roles"]
    others = [
        (role, probe)
        for role, entry in roles.items()
        if role != FIXTURE_ROLE
        for probe in entry.get("probes", [])
        if any(name in probe for name in DEPLOYMENTS)
    ]
    assert others == []
    assert {f"deployment/{name}" for name in DEPLOYMENTS} <= set(roles[FIXTURE_ROLE]["probes"])


@pytest.mark.parametrize("cluster", CLUSTER_NAMES)
@pytest.mark.parametrize("namespace", NAMESPACE_SPELLINGS)
@pytest.mark.parametrize("deployment", DEPLOYMENTS)
def test_a_ledger_with_the_finding_fails(audit_report, check, ledger, deployment: str, namespace: str, cluster: str) -> None:
    """The finding on one of the two Deployments, with its namespace or with an empty one: the check fails and names the phrase."""
    finding = _id(audit_report, cluster, namespace, f"Deployment/{deployment}")
    assert len(finding) <= audit_report.MAX_FINDING_ID
    ledger([_family_id(audit_report, cluster), finding])
    result = _grade(check)
    assert result.status == "fail", (finding, result.reason)
    assert _phrase_for(check, deployment) in result.reason


@pytest.mark.parametrize("cluster", CLUSTER_NAMES)
def test_a_ledger_without_the_finding_passes(audit_report, check, ledger, cluster: str) -> None:
    """The family's finding and a finding on another Deployment of the same namespace: the check passes."""
    ledger([_family_id(audit_report, cluster), _id(audit_report, cluster, NAMESPACE, "Deployment/other-workload")])
    result = _grade(check)
    assert result.status == "pass", result.reason


def test_a_ledger_with_no_family_finding_fails(audit_report, check, ledger) -> None:
    """A run that filed nothing that the case knows did not show that the audit read the fleet."""
    ledger([_id(audit_report, CLUSTER_NAMES[0], NAMESPACE, "Deployment/other-workload")])
    result = _grade(check)
    assert result.status == "fail", result.reason
    for phrase in check["required_phrases"]:
        assert phrase in result.reason


@pytest.mark.parametrize("deployment", DEPLOYMENTS)
def test_phrases_with_the_namespace_do_not_see_a_finding_with_an_empty_namespace(audit_report, check, ledger, deployment: str) -> None:
    """Why the phrases changed: the same ledger, graded with the phrases that held the namespace, passes."""
    finding = _id(audit_report, CLUSTER_NAMES[0], "", f"Deployment/{deployment}")
    ledger([_family_id(audit_report, CLUSTER_NAMES[0]), finding])
    assert _grade(check, forbidden_phrases=PHRASES_WITH_THE_NAMESPACE).status == "pass"
    assert _grade(check).status == "fail"
