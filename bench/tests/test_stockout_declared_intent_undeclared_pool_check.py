"""The check `the-undeclared-pool-is-still-a-finding` of
stockout-declared-intent-no-finding, on ledgers with and without the finding.

The check requires the `single-zone-nodepool` finding of
`pinned-inference-pool`, the pool that the declaration could have taken in.
Two more pools of the seeded fleet have a finding of the same check
(`dev-reserved-pool` on seeded-a and the default pool of seeded-c), so the
check name alone is not enough. Each ledger is graded through
`LedgerIssueContainsVerifier.verify()` with the one HTTP GET faked, as
`test_verifiers.py` does, and each id comes from the audit's own id code.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest
import yaml

from kube_agents_bench import transcript, verifiers
from kube_agents_bench.verifiers import LedgerIssueContainsVerifier

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "agents" / "platform" / "skills" / "fleet-audit" / "scripts")]
import audit_report  # noqa: E402

CASE = REPO / "bench" / "tasks" / "stockout-declared-intent-no-finding" / "task.yaml"
CHECK_NAME = "the-undeclared-pool-is-still-a-finding"
AUDIT = "stockout-prevention"
FORGE_REPO = "kube-agents-evals-36-infra"
ISSUE = 351
RUN_START = datetime(2026, 11, 26, 0, 40, 0, tzinfo=timezone.utc).timestamp()
GENERATED_AT = "2026-11-26T00:53:41.681474+00:00"
PLACE = "kube-agents-evals-36/us-central1-a"
SINGLE_ZONE = "single-zone-nodepool"

# (check, cluster, pool): the three single-zone-nodepool findings of the
# seeded fleet, and two findings of other checks.
PINNED = (SINGLE_ZONE, "seeded-a", "pinned-inference-pool")
DEV_RESERVED = (SINGLE_ZONE, "seeded-a", "dev-reserved-pool")
SEEDED_C_DEFAULT = (SINGLE_ZONE, "seeded-c", "default-pool")
RESERVATION = ("reservation-mismatch-risk", "seeded-a", "missing-reservation-pool")
# Another check on the required pool. Its id sorts after each
# single-zone-nodepool id, so in the id block it follows them.
SPOT_ON_PINNED = ("spot-scarcity-risk", "seeded-a", "pinned-inference-pool")


def _check() -> dict:
    spec = yaml.safe_load(CASE.read_text())["verification_spec"]
    (entry,) = [e for e in spec if e["name"] == CHECK_NAME]
    return entry["check"]


def _finding(check: str, cluster: str, pool: str) -> dict:
    finding = {"check": check, "cluster": f"{PLACE}/{cluster}", "namespace": "", "object": f"NodePool/{pool}", "severity": "major"}
    return {**finding, "id": audit_report.published_id(finding)}


def _ledger(rows: list[tuple[str, str, str]]) -> str:
    """A body in the renderer's shape: findings table, footer, hidden id block."""
    findings = [_finding(*row) for row in rows]
    ids = sorted(finding["id"] for finding in findings)
    table = "\n".join(audit_report._index_row(finding, audit_report.STATE_OPEN, None) for finding in findings)
    return (
        "## Findings\n\n| Finding | Severity | Cluster | State |\n"
        "| ------- | -------- | ------- | ----- |\n"
        f"{table}\n\n---\n\n"
        f"Generated by the Platform Agent `{AUDIT}` watchdog at {GENERATED_AT}. "
        "Findings come from read-only inspection of the live fleet.\n\n"
        f"<!-- audit-findings: {json.dumps(ids, separators=(',', ':'))} -->\n"
        "<!-- audit-id-scheme: 6 -->\n"
    )


@pytest.fixture
def forge(monkeypatch):
    monkeypatch.setenv("BENCH_GITHUB_TOKEN", "ghs_fake")
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    monkeypatch.delenv("BENCH_FORGE", raising=False)
    routes: dict[str, object] = {}

    def fake_get(url: str, tok: str, timeout: float):
        return routes.get(url, (404, {"message": "Not Found"}))

    monkeypatch.setattr(verifiers, "_http_get_json", fake_get)
    return routes


def _grade(routes: dict, body: str) -> verifiers.VerificationResult:
    routes[f"https://api.github.com/repos/gke-agentic/{FORGE_REPO}/issues/{ISSUE}"] = (
        200,
        {"number": ISSUE, "body": body, "labels": [{"name": f"audit:{AUDIT}"}]},
    )
    transcript.set(
        "full output",
        [],
        final_message=f"Stockout prevention: 3 findings across 4 clusters — https://github.com/gke-agentic/{FORGE_REPO}/issues/{ISSUE}",
        started_at=RUN_START,
    )
    return LedgerIssueContainsVerifier(**_check()).verify(5.0)


def test_the_check_reads_the_ids_and_names_the_pool_in_its_pattern():
    check = _check()
    assert check["scope"] == "finding_ids"
    assert "required_phrases" not in check
    (pattern,) = check["required_patterns"]
    assert SINGLE_ZONE in pattern and "nodepool-pinned-inference-pool" in pattern


def test_the_ids_have_the_shape_that_the_pattern_reads():
    assert _finding(*PINNED)["id"] == "single-zone-nodepool.kube-agents-evals-36-us-central1-a-seeded-a._.nodepool-pinned-inference-pool"
    assert _finding(*DEV_RESERVED)["id"] == "single-zone-nodepool.kube-agents-evals-36-us-central1-a-seeded-a._.nodepool-dev-reserved-pool"


PASSING = {
    "the fleet as planted: the pinned pool beside the two other pools": [PINNED, DEV_RESERVED, SEEDED_C_DEFAULT, RESERVATION],
    "the pinned pool alone": [PINNED],
}

FAILING = {
    "the new pool alone": [DEV_RESERVED, RESERVATION],
    "the default pool of seeded-c alone": [SEEDED_C_DEFAULT],
    "the two other pools, and no finding on the pinned pool": [DEV_RESERVED, SEEDED_C_DEFAULT, RESERVATION],
    "no single-zone-nodepool finding": [RESERVATION],
    # The check's name is in one id and the pool's name is in a later id.
    "the new pool, and another check on the pinned pool": [DEV_RESERVED, SPOT_ON_PINNED],
}


@pytest.mark.parametrize("rows", PASSING.values(), ids=list(PASSING))
def test_a_ledger_with_the_finding_on_the_pinned_pool_passes(forge, rows):
    result = _grade(forge, _ledger(rows))
    assert result.status == "pass", result.reason


@pytest.mark.parametrize("rows", FAILING.values(), ids=list(FAILING))
def test_a_ledger_without_the_finding_on_the_pinned_pool_fails(forge, rows):
    result = _grade(forge, _ledger(rows))
    assert result.status == "fail", result.reason
    assert "required patterns absent" in result.reason
