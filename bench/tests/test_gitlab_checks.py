"""``ledger_issue_contains`` and ``pull_request_opened`` on a GitLab project.

Over the recorded, anonymised gitlab.com payloads in ``fixtures/gitlab/``
(see ``test_gitlab_writes.py`` for where they came from): ``issue-open.json``
and ``issue-closed.json`` are one issue as GitLab returned it on create and
on close, ``issue-notes.json`` its notes, ``mr-view.json`` an open merge
request, ``mr-closed.json`` a closed one with its ``mr-commits.json``. A test
that needs a ledger body or a stamp writes it onto the recorded shape; the
shape, the field names and the URL forms are GitLab's own.
"""

from __future__ import annotations

import copy
import json
from datetime import datetime, timezone
from pathlib import Path

import pytest
from kube_agents_bench import forges, github_writes, transcript, verifiers
from kube_agents_bench.verifiers import LedgerIssueContainsVerifier, PullRequestOpenedVerifier

FIXTURES = Path(__file__).parent / "fixtures" / "gitlab"
REPO = "example-group/infra"
PROJECT = "https://gitlab.com/api/v4/projects/example-group%2Finfra"
AUDIT = "compliance-audit"
# The run starts at 14:59:30Z; the ledger is stamped 20s later, !3 opened at
# 14:59:51Z and its head committed at 14:59:48Z.
RUN_START = datetime(2026, 10, 1, 14, 59, 30, tzinfo=timezone.utc)
STAMP = "2026-10-01T14:59:50+00:00"
ISSUE_URL = f"https://gitlab.com/{REPO}/-/work_items/1"
MR3_URL = f"https://gitlab.com/{REPO}/-/merge_requests/3"


def fixture(name: str):
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def ledger_body(stamp: str = STAMP, findings: str = "rbac-overgrant on seeded-a") -> str:
    return (
        f"# Audit ledger\n\n### {findings}\n\n---\n\n"
        f"Generated by the Platform Agent `{AUDIT}` watchdog at {stamp}. "
        "Findings come from read-only inspection of the live fleet.\n\n"
        '<!-- audit-findings: ["rbac-overgrant.seeded-a._.debug-binding"] -->\n'
        "<!-- audit-id-scheme: 2 -->\n"
    )


def ledger(stamp: str = STAMP, closed: bool = False) -> dict:
    issue = fixture("issue-closed.json" if closed else "issue-open.json")
    issue["description"] = ledger_body(stamp)
    issue["labels"] = ["agent:audit", f"audit:{AUDIT}"]
    return issue


@pytest.fixture
def env(monkeypatch):
    monkeypatch.setenv(forges.FORGE_ENV_VAR, "gitlab")
    monkeypatch.setenv("BENCH_GITLAB_TOKEN", "glpat-fake")
    monkeypatch.delenv(forges.GITLAB_HOST_ENV_VAR, raising=False)
    monkeypatch.delenv("BENCH_GITHUB_TOKEN", raising=False)
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)


@pytest.fixture
def gitlab(monkeypatch):
    calls: list[str] = []
    routes: dict[str, object] = {}

    def fake_get(url: str, tok: str, timeout: float):
        calls.append(url)
        return routes.get(url, (404, {"message": "404 Not found"}))

    monkeypatch.setattr(verifiers, "_http_get_json", fake_get)
    return type("GL", (), {"routes": routes, "calls": calls})()


def stash(final_message: str):
    transcript.set("full output", [], final_message=final_message, started_at=RUN_START.timestamp())


def ledger_check(**kw) -> LedgerIssueContainsVerifier:
    return LedgerIssueContainsVerifier(type="ledger_issue_contains", audit=AUDIT, **kw)


def pr_check(**kw) -> PullRequestOpenedVerifier:
    kw.setdefault("owner", "example-group")
    return PullRequestOpenedVerifier(type="pull_request_opened", **kw)


