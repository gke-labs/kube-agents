def route_mr3(gitlab, **overrides) -> dict:
    mr = fixture("mr-view.json")
    mr["changes_count"] = "1"
    mr.update(overrides)
    gitlab.routes[f"{PROJECT}/merge_requests/3"] = (200, mr)
    gitlab.routes[f"{PROJECT}/repository/commits/{mr['sha']}"] = (200, fixture("commit-by-sha.json"))
    return mr


def test_a_merge_request_opened_in_the_run_passes(env, gitlab):
    route_mr3(gitlab)
    stash(f"Opened {MR3_URL}")
    result = pr_check().verify(30)
    assert result.success is True, result.reason
    assert result.raw == {
        "pull_request": f"{REPO}!3",
        "created_at": "2026-10-01T14:59:51.560000+00:00",
        "updated_at": "2026-10-01T14:59:52.865000+00:00",
        "changed_files": 1,
        "head_committed_at": "2026-10-01T14:59:48+00:00",
    }


def test_a_closed_merge_request_is_rejected_and_a_merged_one_is_not(env, gitlab):
    route_mr3(gitlab, state="closed")
    stash(f"Opened {MR3_URL}")
    result = pr_check().verify(30)
    assert result.success is False
    assert "closed without being merged" in result.reason
    route_mr3(gitlab, state="merged")
    assert pr_check().verify(30).success is True


