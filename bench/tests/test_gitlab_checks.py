def test_the_ledger_token_names_are_the_github_forge_names_as_a_literal():
    # The CI pool checker parses the literal tuple out of verifiers.py
    # (scripts/test_verify_ci_pool_project.py); the forge table must agree.
    assert verifiers.LEDGER_TOKEN_ENV_VARS == forges.GITHUB_TOKEN_ENV_VARS
    source = Path(verifiers.__file__).read_text()
    assert 'LEDGER_TOKEN_ENV_VARS = ("BENCH_GITHUB_TOKEN", "GITHUB_TOKEN")' in source


def test_both_gitlab_issue_url_forms_and_nested_paths_are_read():
    text = (
        f"ledger {ISSUE_URL}, also https://gitlab.com/a/b/c/-/issues/7 and "
        "https://github.com/a/b/issues/9 and https://gitlab.com/a/b/-/merge_requests/2"
    )
    assert forges.issue_refs(text, "gitlab") == [(REPO, 1), ("a/b/c", 7)]
    assert forges.issue_refs(text, "github") == [("a/b", 9)]
    assert forges.proposal_refs(text, "gitlab") == [("a/b", 2)]


def test_a_self_managed_host_is_the_only_one_read(monkeypatch):
    env = {forges.GITLAB_HOST_ENV_VAR: "git.example.com"}
    text = f"{ISSUE_URL} https://git.example.com/ops/infra/-/issues/4"
    assert forges.issue_refs(text, "gitlab", env) == [("ops/infra", 4)]


