def test_a_closed_gitlab_ledger_is_a_false_clean_when_closed_in_the_run(env, gitlab):
    issue = ledger(stamp="2026-09-30T10:00:00+00:00", closed=True)
    issue["closed_at"] = "2026-10-01T14:59:40.000Z"
    gitlab.routes[f"{PROJECT}/issues/1"] = (200, issue)
    gitlab.routes[f"{PROJECT}/issues/1/notes?sort=desc&order_by=created_at&per_page=100"] = (
        200,
        fixture("issue-notes.json"),
    )
    stash(f"Closed as clean: {ISSUE_URL}")
    result = ledger_check().verify(30)
    assert result.success is False
    assert "a false clean" in result.reason
    assert result.raw["reset_by_harness"] is False


def test_the_reset_marker_is_read_from_gitlab_notes_skipping_system_notes(env, gitlab):
    issue = ledger(stamp="2026-09-30T10:00:00+00:00", closed=True)
    issue["closed_at"] = "2026-10-01T14:59:10.000Z"
    marker = fixture("issue-notes.json")[0]
    marker["body"] = f"{verifiers.LEDGER_RESET_MARKER}\nClosed before a repetition."
    marker["created_at"] = "2026-10-01T14:59:08.000Z"
    system = copy.deepcopy(marker)
    system["system"] = True
    notes_url = f"{PROJECT}/issues/1/notes?sort=desc&order_by=created_at&per_page=100"
    gitlab.routes[f"{PROJECT}/issues/1"] = (200, issue)
    stash(f"Ledger: {ISSUE_URL}")

    gitlab.routes[notes_url] = (200, [system])
    assert ledger_check().verify(30).raw["reset_by_harness"] is False

    gitlab.routes[notes_url] = (200, [system, marker])
    result = ledger_check().verify(30)
    assert result.raw["reset_by_harness"] is True
    assert "eval harness's ledger reset" in result.reason


