class RateLimited(Exception):
    """GitLab refused the token under its limit twice over, or once with no
    attempt left to wait for. The caller ends its run rather than visiting
    every project through the cooldown, as the GitHub sweep does; a write
    loop lets this through where it swallows an ordinary fault."""

    def __init__(self, exc: urllib.error.HTTPError):
        super().__init__(f"GitLab answered HTTP 429 on {exc.url} with no retry left to wait; the token is rate-limited")
        self.cause = exc

pause = time.sleep
ResetError = ledgers.ResetError


def api_root(host: str = DEFAULT_HOST) -> str:
    return f"https://{host}/api/v4"


def expected_project(path: str, project: str) -> None:
    """Refuse unless `path` is the leased project's own GitLab project."""
    if not project:
        raise ResetError("no PROJECT_ID: refusing to touch a GitLab project for an unnamed lease")
    group, _, name = path.partition("/")
    if not group or not name or "/" in name:
        raise ResetError(f"{path!r} is not a group/project path")
    if group != GROUP:
        raise ResetError(f"{path} is not in the {GROUP} group, where every pool project lives; refusing to touch it")
    if name != project + PROJECT_SUFFIX:
        raise ResetError(
            f"{path} is not the GitLab project of the leased project {project} "
            f"(expected {GROUP}/{project}{PROJECT_SUFFIX}); refusing to touch it"
        )


def encoded(path: str) -> str:
    """A project path as GitLab's `:id`, URL-encoded whole (slash included)."""
    return urllib.parse.quote(path, safe="")


def api(method: str, path: str, token: str, body: dict | None = None, host: str = DEFAULT_HOST):
    """One GitLab call. Returns the decoded body, or None when it is empty."""
    data = None
    headers = {"PRIVATE-TOKEN": token, "Accept": "application/json", "User-Agent": USER_AGENT}
    if body is not None:
        data = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(api_root(host) + path, method=method, headers=headers, data=data)
    with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT_SECONDS) as response:
        raw = response.read()
    if not raw:
        return None
    try:
        return json.loads(raw)
    except ValueError as exc:
        raise OSError(f"GitLab answered {method} {path} with a body that is not JSON: {exc}") from exc


def _transient(exc: BaseException) -> bool:
    if isinstance(exc, urllib.error.HTTPError):
        return exc.code >= RETRYABLE_STATUS_FLOOR or exc.code == TOO_MANY_REQUESTS_CODE
    return isinstance(exc, (OSError, http.client.HTTPException))


def _retry_after(exc: urllib.error.HTTPError, default: float) -> float:
    try:
        asked = int((exc.headers or {}).get(RETRY_AFTER_HEADER, "") or RETRY_AFTER_DEFAULT_SECONDS)
    except (TypeError, ValueError):
        asked = RETRY_AFTER_DEFAULT_SECONDS
    return float(min(max(asked, 1), RETRY_AFTER_MAX_SECONDS)) if exc.code == TOO_MANY_REQUESTS_CODE else default


def call(method: str, path: str, token: str, body: dict | None = None, host: str = DEFAULT_HOST):
    """One GitLab call, tried again after a transient answer: a 5xx or a
    dropped connection twice, a 429 once after its Retry-After and then
    RateLimited. `api` stays the raw seam the tests replace; this is what
    every read and write below uses."""
    limited_once = False
    for delay in (*RETRY_DELAYS_SECONDS, None):
        try:
            return api(method, path, token, body, host)
        except CALL_FAULTS as exc:
            # The 429 case is classified before the last-attempt test, so a
            # second 429 is RateLimited whatever came between the two.
            limited = isinstance(exc, urllib.error.HTTPError) and exc.code == TOO_MANY_REQUESTS_CODE
            if limited and (limited_once or delay is None):
                raise RateLimited(exc) from exc
            if delay is None or not _transient(exc):
                raise
            if limited:
                limited_once = True
                delay = _retry_after(exc, delay)
            print(f"  {method} {path} answered {exc}; trying again in {delay:g}s", file=sys.stderr)
            pause(delay)
    raise AssertionError("unreachable")


def _pages(path: str, query: dict, token: str, host: str, what: str) -> list[dict]:
    """Every item across the pages of a listing, in GitLab's order."""
    found: list[dict] = []
    for page in range(1, MAX_PAGES + 1):
        q = dict(query, per_page=str(PER_PAGE), page=str(page))
        batch = call("GET", f"{path}?{urllib.parse.urlencode(q)}", token, host=host)
        if not isinstance(batch, list) or not all(isinstance(item, dict) for item in batch):
            raise ResetError(f"GitLab answered {what} with a body that is not a list")
        if not batch:
            break
        found.extend(batch)
        if len(batch) < PER_PAGE:
            break
    return found


def labels_of(item: dict) -> set[str]:
    """GitLab lists labels as names; the detail view of some objects as dicts."""
    names = set()
    for label in item.get("labels") or []:
        names.add(str(label.get("name") or "") if isinstance(label, dict) else str(label))
    return names


def author_of(item: dict) -> str:
    return str((item.get("author") or {}).get("username") or "")


def current_login(token: str, host: str = DEFAULT_HOST) -> str:
    """Whose token this is, read rather than written out, so a renamed or
    replaced bot account is followed instead of silently matching nothing (the
    GitHub sweep reads the App's slug from GET /app for the same reason)."""
    me = call("GET", "/user", token, host=host)
    login = str((me or {}).get("username") or "") if isinstance(me, dict) else ""
    if not login:
        raise ResetError("GitLab answered the token's user lookup without a username")
    return login


# --- ledgers ------------------------------------------------------------------


def not_a_ledger_because(issue: dict, audit_id: str | None, bot_login: str = BOT_LOGIN) -> str | None:
    """Why an issue is not a ledger, or None when it is one: the GitHub rule
    with the bot's login in place of the `[bot]` suffix."""
    labels = labels_of(issue)
    if AUDIT_LABEL not in labels:
        return f"no {AUDIT_LABEL} label"
    if audit_id:
        if STREAM_LABEL_PREFIX + audit_id not in labels:
            return f"no {STREAM_LABEL_PREFIX}{audit_id} label"
    elif not any(name.startswith(STREAM_LABEL_PREFIX) for name in labels):
        return f"no {STREAM_LABEL_PREFIX}<id> label"
    if not str(issue.get("title") or "").startswith(TITLE_PREFIX):
        return f"title does not start with {TITLE_PREFIX!r}"
    author = author_of(issue)
    if author != bot_login:
        return f"author {author or '?'} is not {bot_login}"
    return None


def open_ledgers(path: str, token: str, audit_id: str | None, host: str = DEFAULT_HOST, bot_login: str = BOT_LOGIN) -> list[dict]:
    """Every open ledger issue in the project, oldest first; a labelled issue
    that is not one is named on stdout with the reason it stays open."""
    labels = AUDIT_LABEL if not audit_id else f"{AUDIT_LABEL},{STREAM_LABEL_PREFIX}{audit_id}"
    issues = _pages(f"/projects/{encoded(path)}/issues", {"state": "opened", "labels": labels}, token, host, f"the issue listing for {path}")
    found = []
    for issue in issues:
        why = not_a_ledger_because(issue, audit_id, bot_login)
        if why is None:
            found.append(issue)
        else:
            print(f"  #{issue.get('iid', '?')} left open, not a ledger: {why}")
    found.sort(key=lambda issue: int(issue.get("iid") or 0))
    return found


def reset_ledgers(path: str, project: str, build: str, token: str, audit_id: str | None, dry_run: bool, host: str = DEFAULT_HOST, scope: str | None = None, bot_login: str | None = None) -> int:
    """Close the open ledgers; return how many did not close. The GitHub
    reset's contract, note for comment and `state_event` for the close. The
    note's scope follows the audit id unless the caller names one, and the
    bot's login is read from the token unless the caller already holds it."""
    expected_project(path, project)
    scope = scope or (f"before repetition of the {audit_id} stream" if audit_id else "at lease time")
    found = open_ledgers(path, token, audit_id, host, bot_login or current_login(token, host))
    unclosed = []
    for issue in found:
        iid = issue["iid"]
        print(f"  #{iid} {issue.get('title', '')}")
        if dry_run:
            continue
        try:
            call("POST", f"/projects/{encoded(path)}/issues/{iid}/notes", token, {"body": ledgers.closing_comment(build, scope)}, host)
            call("PUT", f"/projects/{encoded(path)}/issues/{iid}", token, {"state_event": "close"}, host)
        except RateLimited:
            raise
        except CALL_FAULTS as exc:
            print(f"  #{iid} did not close ({exc})", file=sys.stderr)
            unclosed.append(iid)
    verb = "would close" if dry_run else "closed"
    what = f"open ledger(s) of the {audit_id} stream" if audit_id else "open ledger(s)"
    print(f"{verb} {len(found) - len(unclosed)} {what} in {path} {scope}")
    return len(unclosed)


# --- the ledger-path probe (kube-agents#2920) ---------------------------------


def _probe_issue_view(issue: dict) -> tuple[set[str], str | None, datetime.datetime | None]:
    """The labels, footer audit id and footer stamp of one issue, read the way
    the bench's ledger check reads them: `description`, bare label names, the
    LAST footer match."""
    match = None
    for match in PROBE_FOOTER_RE.finditer(str(issue.get("description") or "")):
        pass
    if match is None:
        return labels_of(issue), None, None
    try:
        stamp = datetime.datetime.fromisoformat(match.group("stamp"))
    except ValueError:
        return labels_of(issue), match.group("audit").strip(), None
    if stamp.tzinfo is None:
        # The bench's parser reads a naive stamp as UTC rather than dropping it.
        stamp = stamp.replace(tzinfo=datetime.timezone.utc)
    return labels_of(issue), match.group("audit").strip(), stamp


def probe_ledger_path(path: str, project: str, build: str, agent_token: str, ledger_token: str, host: str = DEFAULT_HOST, now: datetime.datetime | None = None) -> tuple[int | None, list[str]]:
    """Open one ledger-shaped issue as the agent, read it back with the
    grader's token, close it through the reset, read the close back; return
    (iid, faults). An empty fault list is a pass. The read-back asks what the
    bench asks of a ledger (the issue by number, its labels, the footer's
    audit id and stamp) and what the reset asks (the title prefix and the
    bot's authorship), since both have to hold for a real ledger to be graded
    and then retired. Every fault names the step, so a red run says which
    half of the path is broken: the agent's write, the read, or the reset."""
    expected_project(path, project)
    now = now or datetime.datetime.now(datetime.timezone.utc)
    faults: list[str] = []
    labels = f"{AUDIT_LABEL},{STREAM_LABEL_PREFIX}{PROBE_AUDIT_ID}"
    body = PROBE_FOOTER.format(audit=PROBE_AUDIT_ID, stamp=now.isoformat())
    # The bot's login first, so a lookup fault creates nothing to retire.
    try:
        bot_login = current_login(agent_token, host)
    except RateLimited:
        raise
    except CALL_FAULTS + (ResetError,) as exc:
        return None, [f"publish: the agent token could not read its own login at {host} ({exc})"]
    try:
        created = _write("POST", f"/projects/{encoded(path)}/issues", agent_token, {"title": PROBE_TITLE, "description": body, "labels": labels}, host)
    except RateLimited:
        raise
    except CALL_FAULTS as exc:
        return None, [f"publish: the agent token could not open an issue in {path} ({exc})"]
    iid = created.get("iid") if isinstance(created, dict) else None
    if not iid:
        return None, [f"publish: GitLab answered the issue create without an iid ({str(created)[:PROBE_REPLY_EXCERPT_CHARS]})"]
    # Read back with the grader's token: the issue by number.
    try:
        seen = call("GET", f"/projects/{encoded(path)}/issues/{iid}", ledger_token, None, host)
    except RateLimited:
        raise
    except CALL_FAULTS as exc:
        faults.append(f"read-back: the ledger token could not read issue #{iid} ({exc})")
        seen = None
    if seen is not None and not isinstance(seen, dict):
        faults.append(f"read-back: GitLab answered the read of issue #{iid} with no object ({str(seen)[:PROBE_REPLY_EXCERPT_CHARS]})")
        seen = None
    elif seen is None and not faults:
        faults.append(f"read-back: GitLab answered the read of issue #{iid} with an empty body")
    not_a_ledger = None
    if isinstance(seen, dict):
        not_a_ledger = not_a_ledger_because(seen, PROBE_AUDIT_ID, bot_login)
        if not_a_ledger:
            faults.append(f"read-back: issue #{iid} does not read as a ledger: {not_a_ledger}")
        _, audit, stamp = _probe_issue_view(seen)
        if audit != PROBE_AUDIT_ID:
            faults.append(f"read-back: issue #{iid} carries no parseable footer for {PROBE_AUDIT_ID} (got {audit!r})")
        elif stamp is None or abs((stamp - now).total_seconds()) > PROBE_MAX_SKEW_SECONDS:
            faults.append(f"read-back: issue #{iid}'s footer stamp did not come back as written ({stamp})")
        if str(seen.get("state") or "") != "opened":
            faults.append(f"read-back: issue #{iid} is {seen.get('state')!r}, not opened")
    # Retire it through the reset, the code that retires real ledgers. An
    # issue the ledger rule refused is one the reset cannot see (it applies
    # the same rule, and so does every later lease), so that one is closed
    # here by number instead: a probe never leaves its issue open.
    try:
        if not_a_ledger:
            _write("POST", f"/projects/{encoded(path)}/issues/{iid}/notes", agent_token, {"body": ledgers.closing_comment(build, PROBE_RESET_SCOPE)}, host)
            _write("PUT", f"/projects/{encoded(path)}/issues/{iid}", agent_token, {"state_event": "close"}, host)
            faults.append(f"reset: issue #{iid} closed by number, since the reset's ledger rule would not have found it")
        else:
            unclosed = reset_ledgers(path, project, build, agent_token, PROBE_AUDIT_ID, False, host, scope=PROBE_RESET_SCOPE, bot_login=bot_login)
            if unclosed:
                faults.append(f"reset: {unclosed} probe ledger(s) did not close in {path}")
    except RateLimited:
        raise
    except CALL_FAULTS + (ResetError,) as exc:
        faults.append(f"reset: issue #{iid} could not be listed or closed in {path} ({exc}); it stays open until the next lease's reset")
        return iid, faults
    try:
        after = call("GET", f"/projects/{encoded(path)}/issues/{iid}", ledger_token, None, host)
        notes = call("GET", f"/projects/{encoded(path)}/issues/{iid}/notes", ledger_token, None, host)
    except RateLimited:
        raise
    except CALL_FAULTS as exc:
        faults.append(f"reset read-back: the ledger token could not read issue #{iid} after the close ({exc})")
        return iid, faults
    if after is None:
        faults.append(f"reset read-back: GitLab answered the read of issue #{iid} after the close with an empty body")
    elif not isinstance(after, dict):
        faults.append(f"reset read-back: GitLab answered the read of issue #{iid} after the close with no object ({str(after)[:PROBE_REPLY_EXCERPT_CHARS]})")
    elif str(after.get("state") or "") != "closed":
        faults.append(f"reset read-back: issue #{iid} is not closed after the reset")
    marked = isinstance(notes, list) and any(str(n.get("body") or "").startswith(RESET_MARKER) for n in notes if isinstance(n, dict))
    if not marked:
        faults.append(f"reset read-back: issue #{iid} carries no note opening with the reset marker")
    return iid, faults


PROBE_LEDGER_TOKEN_ENV = "GITLAB_PROBE_LEDGER_TOKEN"


def probe_ledger_main(argv: list[str] | None = None) -> int:
    """`python3 ci_gitlab_forge.py probe-ledger --path P --project ID --build B
    [--host HOST]`: the lease-time ledger-path probe. The agent token arrives
    in GITLAB_PROBE_TOKEN and the ledger token in GITLAB_PROBE_LEDGER_TOKEN,
    never on argv. Exit 0 on a pass with one line naming the issue; exit 1
    with every fault on stderr."""
    import argparse

    parser = argparse.ArgumentParser(prog="ci_gitlab_forge.py probe-ledger")
    parser.add_argument("--path", required=True)
    parser.add_argument("--project", required=True)
    parser.add_argument("--build", required=True)
    parser.add_argument("--host", default=DEFAULT_HOST)
    args = parser.parse_args(argv)
    agent = os.environ.get(PROBE_TOKEN_ENV, "")
    ledger = os.environ.get(PROBE_LEDGER_TOKEN_ENV, "")
    if not agent or not ledger:
        print("probe-ledger: needs the agent token in %s and the ledger token in %s" % (PROBE_TOKEN_ENV, PROBE_LEDGER_TOKEN_ENV), file=sys.stderr)
        return 2
    try:
        iid, faults = probe_ledger_path(args.path, args.project, args.build, agent, ledger, host=args.host)
    except (RateLimited, ResetError, OSError, http.client.HTTPException, ValueError) as exc:
        print("the ledger path could not be probed in %s: %s" % (args.path, exc), file=sys.stderr)
        return 1
    if faults:
        for fault in faults:
            print(fault, file=sys.stderr)
        return 1
    print("issue #%s opened as the agent, read back with the grader's token, closed by the reset in %s" % (iid, args.path))
    return 0


