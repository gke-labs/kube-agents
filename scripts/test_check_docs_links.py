def _git(root: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=root, check=True, capture_output=True)


def _write(root: Path, rel: str, text: str) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


@unittest.skipUnless(shutil.which("git"), "the checker shells out to git")
class SyntheticRepoTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        # Resolved, because tracked_paths() resolves and /tmp may be a symlink.
        self.root = Path(self._tmp.name).resolve()
        _git(self.root, "init", "-q")
        _write(self.root, PRESENT, "# present\n")
        _write(self.root, ON_DISK_ONLY, "# not added\n")
        self.readme = _write(self.root, "README.md", "\n".join(README_LINES) + "\n")
        self.tool = _write(self.root, "tool.py", "\n".join(TOOL_LINES) + "\n")
        _git(self.root, "add", PRESENT, "README.md", "tool.py")
        for target, value in (("REPO", self.root), ("UNLINKED_ALLOWLIST", frozenset())):
            patcher = mock.patch.object(cdl, target, value)
            patcher.start()
            self.addCleanup(patcher.stop)

    def _track(self, *rels: str, links: dict[str, tuple[str, ...]] | None = None) -> None:
        """Track empty documents; `links` maps a document to sibling documents it links."""
        for rel in rels:
            body = [f"# {rel}"]
            for target in (links or {}).get(rel, ()):
                self.assertEqual(Path(target).parent, Path(rel).parent, "links are written as bare names")
                body.append(f"[{target}]({Path(target).name})")
            _write(self.root, rel, "\n".join(body) + "\n")
        _git(self.root, "add", *rels)

    def _unlinked(self) -> list[str]:
        markdown = cdl.tracked_markdown()
        return cdl.check_unlinked(markdown, cdl.reached_files(markdown, cdl.tracked_code()))

    def test_reports_a_dangling_citation_with_its_line(self) -> None:
        problems = cdl.check_code_file(self.tool, cdl.tracked_paths())
        self.assertEqual(
            problems,
            [
                f"tool.py:3: broken citation -> {MISSING}",
                f"tool.py:4: broken citation -> {ON_DISK_ONLY}",
            ],
        )

    def test_trailing_punctuation_anchor_and_line_ref_are_not_the_path(self) -> None:
        problems = cdl.check_code_file(self.tool, cdl.tracked_paths())
        self.assertFalse([p for p in problems if ":2:" in p or ":5:" in p], problems)

    def test_markdown_links_are_still_checked(self) -> None:
        problems = cdl.check_file(self.readme, cdl.tracked_paths())
        self.assertEqual(problems, [f"README.md:3: broken link -> {MISSING_PLAIN}"])

    def test_a_blob_url_is_not_validated_as_a_link(self) -> None:
        """BLOB_ONLY is not tracked, and the blob link to it is still not a broken link."""
        problems = cdl.check_file(self.readme, cdl.tracked_paths())
        self.assertFalse([p for p in problems if BLOB_ONLY in p], problems)

    def test_reports_a_document_nothing_links(self) -> None:
        self._track(UNLINKED)
        self.assertEqual(self._unlinked(), [f"{UNLINKED}: {cdl.UNLINKED_MESSAGE}"])

    def test_a_blob_url_reaches_its_target_with_or_without_a_query(self) -> None:
        self._track(BLOB_ONLY, QUERY_ONLY)
        self.assertEqual(self._unlinked(), [])

    def test_a_code_citation_reaches_its_target(self) -> None:
        self._track(MISSING)  # cited by tool.py, linked by no document
        self.assertEqual(self._unlinked(), [])

    def test_documents_reached_by_shape_are_exempt(self) -> None:
        self._track(ROOT_FILE, NESTED_README, FAMILY_MEMBER, DEEP_FAMILY_MEMBER, ROOT_DOT_DIR_FILE)
        self.assertEqual(self._unlinked(), [])

    def test_reach_follows_links_from_a_root_and_stops_at_dead_ends(self) -> None:
        """PRESENT, which README.md links, links CHAINED and the allowlisted DEAD_END.

        DEAD_END is reached, so its entry is reported as stale; reach through it
        counts for nothing, so DEAD_END_ONLY, which it alone links, is reported
        as unreached. Both halves fail if the dead-end clauses in
        ``reached_files()`` go: DEAD_END_ONLY then vanishes from the report.
        """
        self._track(
            CHAINED, DEAD_END, DEAD_END_ONLY, CYCLE_A, CYCLE_B,
            links={CYCLE_A: (CYCLE_B,), CYCLE_B: (CYCLE_A,), DEAD_END: (DEAD_END_ONLY,)},
        )
        dead_end = os.path.relpath(DEAD_END, Path(PRESENT).parent)
        _write(self.root, PRESENT, f"# present\n[chained]({Path(CHAINED).name})\n[dead end]({dead_end})\n")
        with mock.patch.object(cdl, "UNLINKED_ALLOWLIST", frozenset({DEAD_END})):
            self.assertEqual(
                self._unlinked(),
                [
                    f"{CYCLE_A}: {cdl.UNLINKED_MESSAGE}",
                    f"{CYCLE_B}: {cdl.UNLINKED_MESSAGE}",
                    f"{DEAD_END_ONLY}: {cdl.UNLINKED_MESSAGE}",
                    f"{DEAD_END}: {cdl.ALLOWLIST_LINKED_MESSAGE}",
                ],
            )

    def test_the_sidebar_decides_which_site_pages_are_reached(self) -> None:
        _write(self.root, cdl.SITE_CONFIG, "\n".join(SITE_CONFIG_LINES) + "\n")
        self._track(SITE_INDEX, SITE_404, SITE_LISTED, SITE_UNLISTED, SITE_AUTOGENERATED, SITE_ROUTED)
